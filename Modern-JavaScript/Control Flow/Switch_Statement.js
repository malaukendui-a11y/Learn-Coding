// switch statement
const grade = "A";

switch(grade){
    case "A":
        console.log("Selamat Anda Mendapatkan A");
        break;
    case "B":
        console.log("Selamat Anda Mendapatkan B");
        break;
    case "C":
        console.log("Selamat Anda Mendapatkan C");
        break;
    case "D":
        console.log("Selamat Anda Mendapatkan D");
        break;
    case "E":
        console.log("Selamat Anda Mendapatkan E");
        break;
    default:
        console.log("Anda Goblok");
}














